@pytest.mark.parametrize("fault", PARSE_FAULTS)
def test_parse_error(tmp_path, fault):
    content, format_name = PARSE_FAULTS[fault]
    path = write(tmp_path, content)
    with pytest.raises(ParseError) as info:
        read_file(path)
    assert format_name in str(info.value)
    assert path in str(info.value)
    assert info.value.__cause__ is not None


@pytest.mark.parametrize(
    "exc",
    [
        ValueError("invented"),
        KeyError("invented"),
        IndexError("invented"),
        TypeError("invented"),
        pd.errors.ParserError("invented"),
        UnicodeDecodeError("utf-8", b"\xff", 0, 1, "invalid start byte"),
    ],
)
def test_parser_content_error_becomes_parse_error(monkeypatch, exc):
    def parse(parse_input):
        raise exc

    fmt = ReaderFormat(name="invented", detect=lambda header: True, parse=parse)
    monkeypatch.setattr("snps.io.readers._FORMATS", (fmt,))
    with pytest.raises(ParseError, match="invented format") as info:
        read_file(b"rs1\t1\t101\tAA\n")
    assert info.value.__cause__ is exc


def test_parse_error_names_bytes_input():
    content, _ = PARSE_FAULTS["text for position"]
    with pytest.raises(ParseError, match="bytes input"):
        read_file(content.encode())


def test_contig_error_shows_header_line(tmp_path):
    content, _ = PARSE_FAULTS["malformed contig line"]
    with pytest.raises(ParseError, match="##contig=ID=1,length=5"):
        read_file(write(tmp_path, content))


@pytest.mark.parametrize("cls", [ParseError, UnsupportedFormatError])
def test_exception_hierarchy(cls):
    assert issubclass(cls, SNPsError)
    assert issubclass(cls, ValueError)
    assert issubclass(SNPsError, Exception)
    assert not issubclass(SNPsError, ValueError)


@pytest.mark.parametrize(
    "exc",
    [
        ProviderFailure("invented"),
        ValueError("invented"),
        KeyError("invented"),
        pd.errors.ParserError("invented"),
    ],
)
def test_provider_error_passes_through(exc):
    with pytest.raises(type(exc)) as info:
        read_file(GSA_NEEDING_PROVIDER.encode(), resources=RaisingResources(exc))
    assert info.value is exc


@pytest.mark.parametrize("as_bytes", [False, True])
def test_read_file_result(tmp_path, as_bytes):
    path = write(tmp_path, FILE_23ANDME)
    data = read_file(FILE_23ANDME.encode() if as_bytes else path)
    expected = pd.DataFrame(
        {
            "chrom": np.array(["1", "2", "X"], dtype=object),
            "pos": np.array([101, 202, 303], dtype=np.uint32),
            "genotype": np.array(["AA", np.nan, "AG"], dtype=object),
        },
        index=pd.Index(["rs1", "rs2", "rs3"], name="rsid", dtype=object),
    ).astype({"chrom": object, "genotype": object})
    pd.testing.assert_frame_equal(data.frame, expected)
    assert not data.phased.any()
    assert data.source == ("23andMe",)
    assert data.build == 37
    assert data.build_detected
    assert data.build_original == 37


@pytest.mark.parametrize(
    "fixture",
    ["tests/input/mapmygenome_new_format.txt", "tests/input/testvcf_phased.vcf"],
)
def test_read_file_matches_reader(fixture):
    resources = FakeResources()
    data = read_file(fixture, resources=resources)
    d = Reader(fixture, resources=resources).read()
    pd.testing.assert_frame_equal(data.frame, d["snps"][["chrom", "pos", "genotype"]])
    if "phased" in d["snps"].columns:
        pd.testing.assert_series_equal(data.phased, d["snps"]["phased"])
    else:
        assert not data.phased.any()
    assert data.source == tuple(d["source"].split(", "))
    assert data.build == d["build"]
    assert data.build_detected == bool(d["build"])
    assert data.build_original == d["build"]


def test_rsids_for_vcf():
    data = read_file(VCF.encode(), rsids={"rs2"})
